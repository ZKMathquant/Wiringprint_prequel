#!/usr/bin/env python3
"""GitHub-side launcher. Starts a Kaggle GPU run and EXITS as soon as Kaggle reports it started,
so GitHub Actions minutes are only spent on the ~1-3 minutes it takes to launch.

  launch.py launch --notebooks all|id1,id2 [--lanes 1|2] [--run-id ...] [--selfcheck] ...
  launch.py status
"""
