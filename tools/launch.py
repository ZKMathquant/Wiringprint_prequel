import base64
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
import time

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import nid_common as C  # noqa: E402
from nid_common import log  # noqa: E402

STUB = r"""# Generated by tools/launch.py - thin bootstrap. In kaggle_secrets mode this file holds NO secrets.
import base64, json, os, pathlib, subprocess, sys, traceback

RUN = json.loads(base64.b64decode("__RUN_B64__").decode())
INLINE = json.loads(base64.b64decode("__INLINE_B64__").decode())


def secret(name):
    v = INLINE.get(name)
    if v:
        return v
    try:
        from kaggle_secrets import UserSecretsClient
        v = UserSecretsClient().get_secret(name)
    except Exception as e:
        print("[stub] secret %s not available via Kaggle Secrets (%s)" % (name, type(e).__name__), flush=True)
        v = None
    return v or os.environ.get(name)


def git(args, cwd, token=None):
    cmd = ["git"]
    if token:
        b = base64.b64encode(("x-access-token:" + token).encode()).decode()
        cmd += ["-c", "http.https://github.com/.extraheader=AUTHORIZATION: basic " + b]
    p = subprocess.run(cmd + args, cwd=cwd, capture_output=True, text=True,
                       env={**os.environ, "GIT_TERMINAL_PROMPT": "0"})
    if p.returncode:
        msg = (p.stdout + p.stderr)
        if token:
            msg = msg.replace(token, "***")
        raise RuntimeError("git %s failed: %s" % (" ".join(args[:2]), msg[-600:]))


try:
    gh, hf = secret("GH_TOKEN"), secret("HF_TOKEN")
    if gh:
        os.environ["GH_TOKEN"] = gh
    if hf:
        os.environ["HF_TOKEN"] = hf
    if not gh:
        print("[stub] FATAL: GH_TOKEN is not available. Kaggle -> this notebook -> Add-ons -> Secrets -> "
              "attach GH_TOKEN (or use secret_mode=inline). Nothing can be saved without it.", flush=True)
        sys.exit(2)
    d = "/tmp/nid_repo"
    os.makedirs(d, exist_ok=True)
    git(["init", "-q"], d)
    git(["remote", "add", "origin", "https://github.com/%s/%s.git" % (RUN["owner"], RUN["repo"])], d)
    git(["fetch", "-q", "--depth", "1", "origin", RUN["sha"]], d, gh)
    git(["checkout", "-q", "FETCH_HEAD"], d)
    sys.path.insert(0, d + "/tools")
    import runner
    sys.exit(runner.main(RUN, pathlib.Path(d)))
except SystemExit:
    raise
except Exception:
    traceback.print_exc()
    sys.exit(1)
"""


# ----------------------------------------------------------------------------- kaggle CLI
def kaggle(args, timeout=600):
    exe = shutil.which("kaggle")
    if not exe:
        sys.exit("kaggle CLI not installed (pip install kaggle)")
    p = subprocess.run([exe] + args, capture_output=True, text=True, timeout=timeout)
    return p.returncode, C.scrub((p.stdout or "") + (p.stderr or ""))


def parse_state(text):
    t = text.lower()
    if re.search(r"404|not found|does not exist|could not find", t):
        return "missing"
    m = re.search(r'status\s*"?(?:kernelworkerstatus\.)?([a-z_]+)"?', t)
    s = m.group(1) if m else "unknown"
    return {"new": "queued", "queued": "queued", "running": "running", "complete": "complete",
            "error": "error", "cancel_requested": "cancelled", "cancel_acknowledged": "cancelled",
            "cancelacknowledged": "cancelled", "cancelrequested": "cancelled"}.get(s, s)


def kernel_state(slug):
    rc, out = kaggle(["kernels", "status", slug])
    st = parse_state(out)
    if rc != 0 and st not in ("missing",):
        if re.search(r"401|403|unauthor|forbidden", out, re.I):
            return "auth_error", out
    return st, out


def summary(md):
    p = os.environ.get("GITHUB_STEP_SUMMARY")
    if p:
        with open(p, "a") as fh:
            fh.write(md + "\n")
    else:
        print(md)


def setup_env(cfg):
    os.environ["KAGGLE_USERNAME"] = cfg["kaggle_username"]
    if not (os.environ.get("KAGGLE_KEY") or os.environ.get("KAGGLE_API_TOKEN")):
        sys.exit("No Kaggle credentials: set the repo secret KAGGLE_KEY (and optionally KAGGLE_API_TOKEN).")
    C.register_secret(os.environ.get("KAGGLE_KEY"), os.environ.get("KAGGLE_API_TOKEN"),
                      os.environ.get("RUNTIME_GH_TOKEN"), os.environ.get("RUNTIME_HF_TOKEN"))


def slot_slug(cfg, slot):
    return f"{cfg['kaggle_username']}/{cfg['kernel_prefix']}-{slot}"


def wait_idle(slug, timeout_s=600):
    t0, state = time.time(), None
    while True:
        state, out = kernel_state(slug)
        if state == "auth_error":
            sys.exit(f"Kaggle rejected the credentials:\n{out}")
        if state not in ("running", "queued"):
            return state
        if time.time() - t0 > timeout_s:
            sys.exit(f"Slot {slug} is still '{state}' after {timeout_s // 60} min. Another run is using it. "
                     "Wait for it to finish (or cancel it on Kaggle) and launch again.")
        log(f"[launch] slot busy ({state}); waiting...")
        time.sleep(30)


def build_kernel_dir(cfg, slot, run, gpu, inline=None):
    d = pathlib.Path(tempfile.mkdtemp(prefix=f"kernel_{slot}_"))
    slug = f"{cfg['kernel_prefix']}-{slot}"
    meta = {
        "id": f"{cfg['kaggle_username']}/{slug}",
        "title": slug.replace("-", " "),
        "code_file": "main.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true",
        "enable_gpu": "true" if gpu else "false",
        "enable_tpu": "false",
        "enable_internet": "true",
        "dataset_sources": cfg.get("dataset_sources", []),
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": cfg.get("model_sources", []),
    }
    (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    stub = (STUB.replace("__RUN_B64__", base64.b64encode(json.dumps(run).encode()).decode())
                .replace("__INLINE_B64__", base64.b64encode(json.dumps(inline or {}).encode()).decode()))
    (d / "main.py").write_text(stub)
    return d, meta["id"]


def push_kernel(kdir, accelerator, gpu, timeout_s):
    base = ["kernels", "push", "-p", str(kdir)]
    if timeout_s:
        base += ["-t", str(timeout_s)]
    attempts = [base + (["--accelerator", accelerator] if gpu and accelerator else [])]
    if gpu and accelerator:
        attempts.append(base)  # fall back: runner re-checks the GPU type itself
    last = ""
    for i, args in enumerate(attempts):
        for retry in range(3):
            rc, out = kaggle(args)
            last = out
            if re.search(r"successfully pushed", out, re.I):
                if i == 1:
                    log("[launch] WARNING: --accelerator was rejected; pushed with Kaggle's default GPU. "
                        "The runner will refuse to run if it is not a T4.")
                return out
            if re.search(r"accelerator", out, re.I) and i == 0 and len(attempts) > 1:
                break  # try without the flag
            if re.search(r"quota|phone|verify|permission|unauthor|forbidden|401|403|invalid", out, re.I):
                sys.exit(f"Kaggle refused the push:\n{out}\n\nCommon causes: GPU quota used up, account not "
                         "phone-verified (needed for GPU + internet), wrong KAGGLE_USERNAME/KAGGLE_KEY.")
            log(f"[launch] push attempt {retry + 1} failed: {out.strip()[-300:]}")
            time.sleep(15 * (retry + 1))
    sys.exit(f"Kaggle push failed:\n{last}")


def verify_started(slug, prior, wait_s=420):
    """Return the state once Kaggle shows queued/running. Terminal states seen in the first 90 s are
    the PREVIOUS version's and are ignored."""
    t0 = time.time()
    state = prior
    while time.time() - t0 < wait_s:
        time.sleep(20)
        state, out = kernel_state(slug)
        age = time.time() - t0
        if state in ("queued", "running"):
            return state
        if state in ("error", "cancelled") and age > 90:
            sys.exit(f"Kaggle reports '{state}' for {slug} right after launch:\n{out}")
        if state == "complete" and age > 90:
            return "complete"
    sys.exit(f"Could not confirm the run started within {wait_s}s (last state '{state}'). Check {slug} on Kaggle.")


# ----------------------------------------------------------------------------- commands
def resolve(spec, cfg):
    ids = list(cfg["default_order"]) if spec.strip().lower() in ("all", "") else \
        [s.strip() for s in re.split(r"[,\s]+", spec) if s.strip()]
    bad = [i for i in ids if i not in cfg["notebooks"]]
    if bad:
        sys.exit(f"Unknown notebook ids {bad}. Available: {', '.join(cfg['notebooks'])}")
    return list(dict.fromkeys(ids))


def make_run_id(label):
    rid = C.utcnow().strftime("%Y%m%d-%H%M%S")
    lab = re.sub(r"[^a-z0-9]+", "-", (label or "").lower()).strip("-")[:24]
    return f"{rid}-{lab}" if lab else rid


def cmd_launch(a):
    cfg = C.load_config()
    setup_env(cfg)
    repo_full = os.environ.get("GITHUB_REPOSITORY", f"{cfg['owner']}/{cfg['repo']}")
    owner, repo = repo_full.split("/", 1)
    sha = a.sha or os.environ.get("GITHUB_SHA", "")
    branch = a.branch or os.environ.get("GITHUB_REF_NAME") or cfg.get("branch", "main")
    if not sha:
        sys.exit("No commit sha (GITHUB_SHA or --sha)")
    slot = a.slot or "a"
    inline = {}
    if cfg.get("secret_mode") == "inline":
        inline = {k: v for k, v in (("GH_TOKEN", os.environ.get("RUNTIME_GH_TOKEN")),
                                    ("HF_TOKEN", os.environ.get("RUNTIME_HF_TOKEN"))) if v}

    if a.selfcheck:
        run = {"mode": "selfcheck", "owner": owner, "repo": repo, "branch": branch, "sha": sha,
               "run_id": "selfcheck", "slot": slot}
        kdir, slug = build_kernel_dir(cfg, slot, run, gpu=False, inline=inline)
        prior = wait_idle(slug)
        out = push_kernel(kdir, None, False, 1800)
        log(out.strip())
        st = verify_started(slug, prior)
        summary(f"### Self-check started on Kaggle\nkernel `{slug}` is `{st}` (CPU, ~1-2 min). "
                "Open the kernel log on Kaggle to read the `[selfcheck]` lines.")
        return

    queue = resolve(a.notebooks, cfg)
    if a.resume_from and len(queue) != 1:
        sys.exit("resume_from only makes sense with exactly one notebook.")
    run_id = a.run_id or make_run_id(a.label)
    lanes = int(a.lanes or 1)
    errors = []
    if lanes > 1 and not a.slot:
        lanes = min(lanes, cfg.get("kernel_slots", 2), len(queue), 2)
        lane_lists = [queue[i::lanes] for i in range(lanes)]
        for idx in range(1, lanes):
            slot_n = chr(ord("a") + idx)
            ins = {"notebooks": ",".join(lane_lists[idx]), "run_id": run_id, "slot": slot_n, "lanes": "1",
                   "on_failure": a.on_failure, "label": "", "resume_from": "", "selfcheck": "false", "pin_sha": sha}
            st, js, _ = C.gh_api("POST", f"/repos/{owner}/{repo}/actions/workflows/run.yml/dispatches",
                                 os.environ.get("GH_TOKEN"), {"ref": branch, "inputs": ins})
            if st != 204:
                errors.append(f"could not start lane {slot_n} ({lane_lists[idx]}): HTTP {st} {js.get('message', '')}")
            else:
                log(f"[launch] lane {slot_n} dispatched: {lane_lists[idx]}")
        queue = lane_lists[0]
    head, rest = queue[0], queue[1:]
    if (C.ROOT / "runs" / run_id / head).exists():
        sys.exit(f"runs/{run_id}/{head} already exists - successful runs are frozen. Use a new run_id.")

    run = {"mode": "run", "owner": owner, "repo": repo, "branch": branch, "sha": sha, "run_id": run_id,
           "notebook": head, "queue_rest": rest, "on_failure": a.on_failure, "slot": slot,
           "resume_from": a.resume_from or ""}
    kdir, slug = build_kernel_dir(cfg, slot, run, gpu=True, inline=inline)
    log(f"[launch] run {run_id}: {head} on {slug} (queue after: {rest or 'none'})")
    prior = wait_idle(slug)
    out = push_kernel(kdir, cfg.get("accelerator"), True, cfg["session_limit_hours"] * 3600)
    log(out.strip())
    url = (re.search(r"https://www\.kaggle\.com/\S+", out) or [f"https://www.kaggle.com/code/{slug}"])
    url = url if isinstance(url, str) else url[0]
    state = verify_started(slug, prior)
    md = (f"### Kaggle run started\n| | |\n|---|---|\n| run id | `{run_id}` |\n| notebook | `{head}` |\n"
          f"| kernel | [{slug}]({url}) |\n| state | `{state}` |\n| queued after it | {', '.join(rest) or '-'} |\n"
          f"| results will appear in | `runs/{run_id}/{head}/` (or `failed/...`) |\n")
    if errors:
        md += "\n**Warnings:** " + "; ".join(errors)
    summary(md)
    log("[launch] started - this job now exits; Kaggle pushes the results back when it finishes.")
    if errors:
        sys.exit("; ".join(errors))


def cmd_status(a):
    cfg = C.load_config()
    setup_env(cfg)
    rows = ["### Kaggle slots", "| slot | kernel | state |", "|---|---|---|"]
    bad = []
    for i in range(cfg.get("kernel_slots", 2)):
        slot = chr(ord("a") + i)
        slug = slot_slug(cfg, slot)
        st, _ = kernel_state(slug)
        if st == "auth_error":
            bad.append(slug)
        rows.append(f"| {slot} | [{slug}](https://www.kaggle.com/code/{slug}) | `{st}` |")
    for base in ("runs", "failed"):
        rows += ["", f"### {base}/ (latest 15)", ""]
        d = C.ROOT / base
        entries = []
        if d.is_dir():
            for r in sorted((p for p in d.iterdir() if p.is_dir()), reverse=True)[:15]:
                for nb in sorted(p.name for p in r.iterdir() if p.is_dir()):
                    entries.append(f"- `{r.name}/{nb}`")
        rows += entries or ["- (none yet)"]
    summary("\n".join(rows))
    if bad:
        sys.exit(f"Kaggle rejected the credentials while reading {bad}. Check KAGGLE_KEY / KAGGLE_API_TOKEN secrets.")


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    l = sub.add_parser("launch")
    l.add_argument("--notebooks", default="all")
    l.add_argument("--lanes", default="1")
    l.add_argument("--run-id", dest="run_id", default="")
    l.add_argument("--label", default="")
    l.add_argument("--slot", default="")
    l.add_argument("--on-failure", dest="on_failure", default="continue", choices=["continue", "stop"])
    l.add_argument("--resume-from", dest="resume_from", default="")
    l.add_argument("--selfcheck", action="store_true")
    l.add_argument("--sha", default="")
    l.add_argument("--branch", default="")
    sub.add_parser("status")
    a = ap.parse_args()
    {"launch": cmd_launch, "status": cmd_status}[a.cmd](a)


if __name__ == "__main__":
    main()
